export type SampleId = (typeof samples)[number]['id']
export type Library = 'standard' | 'blueprint'
export type Theme = 'light' | 'dark'

export function previewSearch(search: Record<string, unknown>) {
    return {
        theme: search.theme === 'light' ? ('light' as const) : ('dark' as const),
        filter: typeof search.filter === 'string' ? search.filter : '',
    }
}

export function matchingSamples(filter: string) {
    const query = filter.trim().toLowerCase()

    return samples.filter((sample) => {
        const text = `${sample.title} ${sample.standard} ${sample.blueprint} ${sample.group}`

        return text.toLowerCase().includes(query)
    })
}
