import { readFile, writeFile, access } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = dirname(fileURLToPath(import.meta.resolve('@blueprintjs/icons/package.json')))
const metadata = JSON.parse(await readFile(join(packageRoot, 'icons.json'), 'utf8'))

if (!Array.isArray(metadata)) {
    throw new Error('Blueprint icon metadata must be an array.')
}

const names = metadata.map(icon => {
    if (typeof icon !== 'object' || icon === null || typeof icon.iconName !== 'string') {
        throw new Error('Blueprint icon metadata contains an invalid name.')
    }

    if (!/^[a-z0-9-]+$/.test(icon.iconName)) {
        throw new Error(`Unsupported Blueprint icon name: ${icon.iconName}`)
    }

    return icon.iconName
}).sort()

const entries = []

for (const name of names) {
    await Promise.all([16, 20].map(size => access(join(packageRoot, `lib/esm/generated/${size}px/paths/${name}.js`))))

    entries.push(`    '${name}': {
        16: () => import('@blueprintjs/icons/lib/esm/generated/16px/paths/${name}.js'),
        20: () => import('@blueprintjs/icons/lib/esm/generated/20px/paths/${name}.js'),
    },`)
}

const source = `// Generated by scripts/generate-icon-loaders.mjs from the installed Blueprint icon package.
import type { IconName, IconGrid, IconPathsLoader } from './types'

export const iconLoaders = {
${entries.join('\n')}
} satisfies Record<IconName, Record<IconGrid, IconPathsLoader>>
`

await writeFile(new URL('../src/icons/loaders.ts', import.meta.url), source)
console.log(`Generated individual 16px and 20px loaders for ${names.length} Blueprint icons.`)
